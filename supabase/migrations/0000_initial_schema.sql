-- 1. Custom Types
create type public.user_role as enum ('admin', 'volunteer', 'merchant', 'victim');
create type public.transaction_type as enum ('AID_DISBURSEMENT', 'PURCHASE', 'FUNDS_RETURN');

-- 2. Profiles Table
create table public.profiles (
  id uuid not null primary key default gen_random_uuid(),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  full_name text,
  role user_role not null default 'victim'::user_role
);
comment on table public.profiles is 'Stores user profile information.';

-- 3. Wallets Table
create table public.wallets (
  id uuid not null primary key default gen_random_uuid(),
  created_at timestamp with time zone not null default now(),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  balance numeric(10, 2) not null default 0.00,
  unique(profile_id)
);
comment on table public.wallets is 'Stores the current balance for each user profile.';

-- 4. Ledger Table (Append-Only)
create table public.ledger (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  wallet_id uuid not null references public.wallets(id),
  amount numeric(10, 2) not null,
  transaction_type transaction_type not null,
  idempotency_key uuid not null,
  description text,
  metadata jsonb
);
comment on table public.ledger is 'Append-only audit trail of all transactions.';

-- Add a unique constraint for idempotency to prevent double entries.
alter table public.ledger add constraint ledger_idempotency_key_key unique (idempotency_key);

-- 5. Triage Sessions Table
create table public.triage_sessions (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  victim_id uuid not null references public.profiles(id),
  last_message text,
  risk_score float,
  escalated boolean not null default false,
  notes text
);
comment on table public.triage_sessions is 'Stores AI triage sessions that may need human intervention.';

-- 6. Indexes for performance
create index on public.wallets (profile_id);
create index on public.ledger (wallet_id);
create index on public.triage_sessions (victim_id);



-- 8. Stored Procedure for Purchases (RPC)
create or replace function public.process_aid_purchase(
  victim_profile_id uuid,
  merchant_profile_id uuid,
  purchase_amount numeric,
  idempotency_key uuid
)
returns text
language plpgsql
-- SECURITY DEFINER is used to execute the function with the privileges of the owner.
-- This is necessary to update tables that the calling user may not have direct access to.
-- Ensure the function owner has the necessary permissions.
as $$
declare
  victim_wallet_id uuid;
  merchant_wallet_id uuid;
  victim_current_balance numeric;
  transaction_description text;
  merchant_name text;
  victim_name text;
begin
  -- 1. Get wallet IDs for victim and merchant
  select id, (select full_name from public.profiles where id = victim_profile_id) into victim_wallet_id, victim_name from public.wallets where profile_id = victim_profile_id;
  select id, (select full_name from public.profiles where id = merchant_profile_id) into merchant_wallet_id, merchant_name from public.wallets where profile_id = merchant_profile_id;

  if victim_wallet_id is null then
    raise exception 'Victim wallet not found';
  end if;

  if merchant_wallet_id is null then
    raise exception 'Merchant wallet not found';
  end if;

  -- 2. Check victim's balance (within a transaction lock)
  select balance into victim_current_balance from public.wallets where id = victim_wallet_id for update;

  if victim_current_balance < purchase_amount then
    raise exception 'Insufficient funds';
  end if;

  -- 3. Insert debit for victim
  -- The unique constraint on idempotency_key will prevent duplicates and roll back the transaction.
  insert into public.ledger (wallet_id, amount, transaction_type, idempotency_key, description, metadata)
  values (victim_wallet_id, -purchase_amount, 'PURCHASE'::transaction_type, idempotency_key, 'Purchase at ' || merchant_name, jsonb_build_object('merchant_profile_id', merchant_profile_id));

  -- 4. Insert credit for merchant
  insert into public.ledger (wallet_id, amount, transaction_type, idempotency_key, description, metadata)
  values (merchant_wallet_id, purchase_amount, 'PURCHASE'::transaction_type, idempotency_key, 'Payment from ' || victim_name, jsonb_build_object('victim_profile_id', victim_profile_id));

  -- 5. Update balances
  update public.wallets set balance = balance - purchase_amount where id = victim_wallet_id;
  update public.wallets set balance = balance + purchase_amount where id = merchant_wallet_id;

  return 'Purchase successful';
end;
$$;


-- Function for disbursing aid
create or replace function public.disburse_aid(
  victim_profile_ids uuid[],
  disbursement_amount numeric,
  idempotency_key_prefix text
)
returns text
language plpgsql
as $$
declare
  victim_id uuid;
  victim_wallet_id uuid;
  generated_idempotency_key uuid;
begin
  if disbursement_amount <= 0 then
    raise exception 'Disbursement amount must be positive';
  end if;

  foreach victim_id in array victim_profile_ids
  loop
    select id into victim_wallet_id from public.wallets where profile_id = victim_id;

    if victim_wallet_id is not null then
      -- Generate a unique idempotency key for each victim to allow for partial retries if the whole batch fails
      generated_idempotency_key := gen_random_uuid();

      -- Use a sub-transaction block to handle potential duplicate idempotency keys gracefully
      begin
        -- Insert credit record
        insert into public.ledger (wallet_id, amount, transaction_type, idempotency_key, description, metadata)
        values (victim_wallet_id, disbursement_amount, 'AID_DISBURSEMENT'::transaction_type, generated_idempotency_key, 'Aid Disbursement', jsonb_build_object('batch_idempotency_prefix', idempotency_key_prefix));

        -- Update wallet balance
        update public.wallets set balance = balance + disbursement_amount where id = victim_wallet_id;
      exception
        when unique_violation then
          raise warning 'Idempotency key conflict for victim %, skipping disbursement.', victim_id;
      end;
    else
      raise warning 'Wallet for victim % not found, skipping disbursement.', victim_id;
    end if;
  end loop;

  return 'Disbursement process completed';
end;
$$;


-- Function to register a new victim and create a wallet
create or replace function public.register_victim(
  full_name text
)
returns uuid
language plpgsql
as $$
declare
  new_profile_id uuid;
begin
  -- Insert the new profile
  insert into public.profiles (full_name, role)
  values (full_name, 'victim')
  returning id into new_profile_id;

  -- Create a corresponding wallet
  insert into public.wallets (profile_id, balance)
  values (new_profile_id, 0);

  return new_profile_id;
end;
$$;
